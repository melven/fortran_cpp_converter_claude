"""Module -> header + source, pFUnit test module -> googletest source."""
import os

from .model import cls, lname, items_of, Var
from .prepass import PF_MARK, CPP_MARK, BLANK_MARK
from .translate import Translator, Untranslatable, TODO, par, is_zero

BANNER = "// Generated by f2cpp from {src} -- review all TODO(f2cpp) markers."


class ModuleEmitter:
    def __init__(self, program, module, report, src_name):
        self.prog, self.mod, self.report, self.src = program, module, report, src_name
        self.cfg = program.cfg
        self.ns = program.namespace(module.name)

    def tr(self, proc=None):
        return Translator(self.prog, self.mod, proc, self.report)

    # ------------------------------------------------------------------ declarations
    def var_decl(self, tr, v, member=False):
        """declaration of a local / member / module variable (without trailing ';')"""
        t, st = tr.cpp_type(v), tr.storage(v)
        code = f"{t}\0{v.cname}"
        sizes = []
        for lo, hi in v.dims:
            if hi is None:
                sizes = []
                break
            if lo is None:
                sizes.append(tr.expr(hi).code)
            else:
                h, l = tr.expr(hi), tr.expr(lo)
                if l.code.lstrip("-").isdigit():
                    sizes.append(tr.minus(hi, int(l.code) - 1))
                else:
                    sizes.append(f"{par(h, 70)} - {par(l, 70, True)} + 1")
        if v.init is not None:
            if lname(v.init).replace(" ", "").endswith("null()"):
                return code + " = nullptr" if st == "ptr" else code
            x = tr.expr(v.init)
            if v.rank > 0 and x.rank == 0:
                if st != "eigen" or not sizes:
                    raise Untranslatable("array-initialisation")
                fn = "Zero" if is_zero(x.code) else "Constant"
                args = sizes if fn == "Zero" else sizes + [x.code]
                return f"{code} = {t}::{fn}({', '.join(args)})"
            return f"{code} = {tr.matrix(x)}"
        if st == "ptr":
            self.report.add("todo", "raw-pointer")
            return code + f" = nullptr /* {TODO}: non-owning Fortran pointer */"
        if sizes and not member:
            if st == "flat":
                return f"{code}({' * '.join(f'({d})' if not d.isalnum() else d for d in sizes)})"
            if st in ("eigen", "objmat"):
                return f"{code}({', '.join(sizes)})"
            if st in ("vec3", "stdvec"):
                return f"{code}({tr.nested_ctor(v, sizes)})"
        elif sizes and member:
            if st == "eigen":
                fn = f"{t}({', '.join(sizes)})"
                return f"{code} = {fn}"
            self.report.add("todo", "fixed-size-member")
            return code + f" /* {TODO}: fixed size ({', '.join(sizes)}) */"
        return code

    def decl_stmt(self, tr, stmt, vars_, ind, prefix="", skip=(), member=False):
        """emit one Fortran declaration statement"""
        names = [lname(e.items[0]) for e in items_of(stmt.items[2])]
        decls = []          # [type, [declarators]]: entities of equal type share one statement
        for n in names:
            v = vars_[n]
            if n in skip or v.alias or (n == tr.err and v.base == "integer" and v.rank == 0):
                continue
            try:
                pre = prefix
                if v.has("parameter"):
                    pre += "const "
                elif (v.has("save") or v.init is not None) and tr.proc is not None:
                    pre += "static "
                t, d = self.var_decl(tr, v, member).split("\0")
                t = pre + t
                if decls and decls[-1][0] == t and not t.endswith("*") and "/*" not in d:
                    decls[-1][1].append(d)
                else:
                    decls.append([t, [d]])
                self.report.add("translated", "declaration")
            except Untranslatable as e:
                self.report.add("untranslated", "declaration:" + e.category)
                tr.fortran_comment(stmt, ind, f"declaration of '{v.cname}' not translated ({e.category})")
        for t, ds in decls:
            tr.emit(ind, f"{t} {', '.join(ds)};")
        self.warn_lower_bounds(tr, [vars_[n] for n in names if n not in skip], ind)

    def warn_lower_bounds(self, tr, variables, ind):
        """C++ arrays are 0-based; indices of arrays with a Fortran lower bound /= 1 are shifted"""
        for v in variables:
            if v.has("pointer") and v.rank > 0 and not v.alias:
                self.report.add("todo", "array-pointer")
                tr.emit(ind, f"// {TODO}: Fortran array pointer '{v.cname}' is translated as an owning array "
                             "(no aliasing of its target)")
            lbs = [str(lo).replace(" ", "") for lo, _ in v.dims if lo is not None]
            if any(lb not in ("0", "1") for lb in lbs):
                self.report.add("todo", "lower-bound")
                tr.emit(ind, f"// {TODO}: '{v.cname}' has lower bound(s) {', '.join(lbs)} in Fortran; "
                             "indices are shifted accordingly, check its uses")

    def signature(self, tr, p, decl, qualify=""):
        """-> (return type, name, parameter list, trailing qualifiers)"""
        params = []
        dummies = [a for a in p.args if a != tr.err and a != p.pass_arg]
        n_opt = 0
        for a in reversed(dummies):
            if p.vars[a].opt_kind:
                n_opt += 1
            else:
                break
        for i, a in enumerate(dummies):
            v = p.vars[a]
            s = f"{tr.param_type(v)} {v.cname}"
            if decl and v.opt_kind and i >= len(dummies) - n_opt:
                s += " = std::nullopt"
            params.append(s)
        ret = "void"
        if p.kind == "function":
            ret = tr.cpp_type(p.vars[p.result]) if p.result in p.vars else "auto"
        name = qualify + (p.bind_name if p.method_of else (p.generic or p.cname))
        const = " const" if p.pass_arg and p.vars[p.pass_arg].intent == "in" else ""
        return ret, name, ", ".join(params), const

    def proto(self, tr, p, decl=True, qualify=""):
        ret, name, params, const = self.signature(tr, p, decl, qualify)
        tn = self.prog.type_name(p.method_of).split("::")[-1] if p.method_of else ""
        if name.endswith("~"):
            return f"{qualify}~{tn}()"
        if p.is_ctor:
            return f"{qualify}{tn}({params})"
        return f"{ret} {name}({params}){const}"

    def warn_name(self, tr, name, ind):
        spellings = self.prog.inconsistent_proc_case(name)
        if spellings:
            self.report.add("todo", "inconsistent-name-case")
            tr.emit(ind, f"// {TODO}: name is spelled inconsistently in the Fortran source: "
                         + ", ".join(spellings))

    def doc(self, tr, p, ind):
        for c in p.doc:
            if not str(c).startswith((PF_MARK, CPP_MARK, BLANK_MARK)):
                tr.comment(c, ind)

    # ------------------------------------------------------------------ class
    def emit_type(self, tr, t, ind):
        prog = self.prog
        name = prog.type_name(t.name)
        poly = prog.polymorphic(t)
        if prog.inconsistent_case(t.name):
            self.report.add("todo", "inconsistent-type-case")
            tr.emit(ind, f"// {TODO}: type name is spelled inconsistently in the Fortran source: "
                         + ", ".join(sorted(prog.spellings[t.name])))
        base = f" : public {prog.type_name(t.parent, self.mod)}" if t.parent else ""
        tr.emit(ind, f"class {name}{base} {{")
        tr.emit(ind, "public:")
        mine = [p for p in t.module.procs.values() if p.method_of == t.name]
        has_dtor = any(p.bind_name == "~" for p in mine)
        if any(p.is_ctor for p in mine) or has_dtor:
            tr.emit(ind + 1, f"{name}() = default;")
        if has_dtor:    # a user-declared destructor suppresses the implicit move operations
            tr.emit(ind + 1, f"{name}(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}({name}&&) = default;")
            tr.emit(ind + 1, f"{name}& operator=(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}& operator=({name}&&) = default;")
        if poly and not t.parent and not any(p.bind_name == "~" for p in mine):
            tr.emit(ind + 1, f"virtual ~{name}() = default;")
        # flatten: fparser spreads components / comments over several nodes
        comps, binds = [], []
        for part in t.node.content[1:-1]:
            k = cls(part)
            if k == "Component_Part":
                comps += part.content
            elif k == "Comment":
                comps.append(part)
            elif k == "Type_Bound_Procedure_Part":
                n = [cls(c) for c in part.content].index("Contains_Stmt")
                comps += part.content[:n]
                binds += part.content[n + 1:]
        prev = None
        for b in binds:
            k = cls(b)
            if k == "Comment":
                tr.comment(b, ind + 1, prev)
                continue
            prev = b
            if k == "Specific_Binding":
                bd = t.bindings[lname(b.items[3])]
                p = prog.binding_proc(t, bd)
                if p is None:
                    self.report.add("untranslated", "binding")
                    tr.fortran_comment(b, ind + 1, "binding to unknown procedure")
                    continue
                ptr = self.tr(p)
                self.doc(tr, p, ind + 1)
                special = self.cfg["constructor_bindings"] + self.cfg["destructor_bindings"]
                if bd.deferred and bd.name in special:
                    tr.emit(ind + 1, f"// deferred '{bd.name}': constructor / destructor of the derived classes")
                    continue
                if bd.deferred:
                    # signature from the abstract interface, name from the binding
                    ret, _, params, const = self.signature(ptr, p, True)
                    self.warn_name(tr, bd.name, ind + 1)
                    tr.emit(ind + 1, f"virtual {ret} {bd.spelling}({params}){const} = 0;")
                    continue
                if not (p.is_ctor or p.is_dtor):
                    self.warn_name(tr, bd.generic or bd.name, ind + 1)
                sig = self.proto(ptr, p)
                if p.is_ctor:
                    sig = ("explicit " if sig.count(",") == 0 and not sig.endswith("()") else "") + sig
                elif p.is_dtor:
                    sig = "virtual " + sig if poly and not t.parent else sig + (" override" if poly else "")
                elif bd.nopass:
                    sig = "static " + sig
                elif poly:
                    sig = sig + " override" if prog.overrides(t, bd.name) else "virtual " + sig
                tr.emit(ind + 1, sig + ";")
            elif k == "Final_Binding":
                tr.emit(ind + 1, f"~{name}();")
            elif k == "Generic_Binding":
                tr.emit(ind + 1, f"// generic '{lname(b.items[1])}': specific procedures are C++ overloads")
        if t.comps:
            if binds or (poly and not t.parent):
                tr.emit(0, "")
            if t.private_comps:
                tr.emit(ind, "private:" if not t.children else "protected:")
            prev = None
            for d in comps:
                if cls(d) == "Comment":
                    tr.comment(d, ind + 1, prev)
                    continue
                if cls(d) == "Data_Component_Def_Stmt":
                    self.decl_stmt(tr, d, t.comps, ind + 1, member=True)
                else:
                    self.report.add("untranslated", "component:" + cls(d))
                    tr.fortran_comment(d, ind + 1, "component not translated")
                prev = d
        tr.emit(ind, "};")

    # ------------------------------------------------------------------ procedures
    def emit_proc(self, tr_out, p, ind, head=None):
        """definition of a procedure appended to tr_out.out"""
        tr = self.tr(p)
        tr.out = tr_out.out
        if head is None:
            qualify = self.prog.type_name(p.method_of) + "::" if p.method_of else ""
            head = self.proto(tr, p, decl=False, qualify=qualify)
        tr.emit(ind, head)
        tr.emit(ind, "{")
        self.warn_lower_bounds(tr, [p.vars[a] for a in p.args if a in p.vars], ind + 1)
        skip = set(p.args)
        body_start = len(tr.out)
        has_result_decl = False
        for part in p.node.content:
            k = cls(part)
            if k == "Specification_Part":
                prev = None
                for d in part.content:
                    kd = cls(d)
                    if kd == "Implicit_Part":
                        tr.block([c for c in d.content if cls(c) == "Comment"], ind + 1)
                    elif kd == "Comment":
                        tr.comment(d, ind + 1, prev)
                    elif kd == "Type_Declaration_Stmt":
                        self.decl_stmt(tr, d, p.vars, ind + 1, skip=skip)
                        has_result_decl |= p.result in [lname(e.items[0]) for e in items_of(d.items[2])]
                        prev = d
                    elif kd in ("Use_Stmt", "Import_Stmt"):
                        pass
                    elif kd == "Interface_Block":       # explicit interfaces of external procedures
                        self.report.add("info", "interface-in-procedure")
                    else:
                        self.report.add("untranslated", "specification:" + kd)
                        tr.fortran_comment(d, ind + 1, "not translated")
            elif k == "Execution_Part":
                if p.kind == "function" and not has_result_decl and p.result in p.vars:
                    tr.emit(ind + 1, f"{tr.cpp_type(p.vars[p.result])} {p.vars[p.result].cname};")
                    has_result_decl = True
                tr.block(part.content, ind + 1)
            elif k == "Internal_Subprogram_Part":
                self.report.add("untranslated", "internal-subprogram")
                tr.fortran_comment(part, ind + 1, "internal procedures not translated")
        while len(tr.out) > body_start and tr.out[-1] == "":
            tr.out.pop()
        while len(tr.out) > body_start + 1 and tr.out[body_start] == "":
            del tr.out[body_start]
        if p.kind == "function" and not tr.out[-1].strip().startswith("return "):
            tr.emit(ind + 1, tr.return_code())
        tr.emit(ind, "}")

    # ------------------------------------------------------------------ module
    def includes(self):
        ext, known = self.cfg["header_ext"], self.cfg["module_headers"]
        res = []
        for u in self.mod.uses:
            if u in self.cfg["ignore_modules"]:
                continue
            h = known.get(u, u + ext)
            if h and f'#include "{h}"' not in res:
                res.append(f'#include "{h}"')
        return res

    def std_includes(self, text, names):
        return [f"#include <{h}>" for h, keys in names if any(k in text for k in keys)]

    def open_ns(self):
        return f"namespace {self.ns} {{"

    def using_other_ns(self):
        res = []
        for m in self.prog.visible(self.mod)[1:]:
            ns = self.prog.namespace(m.name)
            if ns != self.ns and not self.ns.startswith(ns + "::") and f"using namespace {ns};" not in res:
                res.append(f"using namespace {ns};")
        return res

    def generate(self):
        """-> (header text, source text)"""
        mod, cfg = self.mod, self.cfg
        self.report.start(self.src)
        hpp, cpp_priv, cpp = self.tr(), self.tr(), self.tr()
        top = self.tr()          # comments / directives before the module statement
        tree_top = []
        # leading comments of the file (fparser attaches them to the Program node)
        parent = getattr(mod.node, "parent", None)
        if parent is not None:
            for c in parent.content:
                if c is mod.node:
                    break
                if cls(c) == "Comment":
                    tree_top.append(c)
        cpp_directives = [c for c in tree_top if str(c).startswith(CPP_MARK)]
        # first comment block = file header; later blocks (module documentation) become plain
        # comments: as doxygen comments they would document the namespace
        blocks = [[]]
        for c in tree_top:
            if str(c).startswith((CPP_MARK, BLANK_MARK)):
                blocks.append([])
            else:
                blocks[-1].append(c)
        blocks = [b for b in blocks if b] or [[]]
        top.block(blocks[0], 0)
        if not any("@file" in line for line in top.out):
            top.out = [plain_comment(line) for line in top.out]
        mod_doc = self.tr()
        mod_doc.block([c for b in blocks[1:] for c in b], 0)
        mod_doc.out = [plain_comment(line) for line in mod_doc.out]
        dirs = self.tr()
        dirs.block(cpp_directives, 0)

        types_fwd = [f"class {self.prog.type_name(t)};" for t in mod.types]
        pending, prev = [], None
        spec = [p for p in mod.node.content if cls(p) == "Specification_Part"]
        for s in (spec[0].content if spec else []):
            k = cls(s)
            if k == "Implicit_Part":
                pending += [c for c in s.content if cls(c) == "Comment"]
                continue
            if k == "Comment":
                pending.append(s)
                continue
            if k in ("Use_Stmt", "Access_Stmt"):
                pending = [c for c in pending if str(c).startswith(BLANK_MARK)][:1]
                continue
            if k == "Type_Declaration_Stmt":
                names = [lname(e.items[0]) for e in items_of(s.items[2])]
                for n in names:
                    v = mod.vars[n]
                    public = mod.is_public(n, v.access) or mod.is_test
                    sink = hpp if public and not mod.is_test else cpp_priv
                    sink.block(pending, 1 if sink is cpp_priv else 0)
                    pending = []
                    if not v.has("parameter"):
                        self.report.add("todo", "module-variable")
                        sink.emit(1 if sink is cpp_priv else 0, f"// {TODO}: module variable (global state)")
                    one = type("S", (), {"items": (s.items[0], s.items[1], _One(s, n))})()
                    self.decl_stmt(sink, one, mod.vars, 1 if sink is cpp_priv else 0,
                                   prefix="inline " if sink is hpp else "")
            elif k == "Derived_Type_Def":
                hpp.block(pending, 0)
                pending = []
                self.emit_type(hpp, mod.types[lname(s.content[0].items[1])], 0)
            elif k == "Interface_Block":
                head = s.content[0].items[0]
                if head is not None and cls(head) != "Name" and str(head).upper() != "ABSTRACT":
                    self.report.add("untranslated", "interface:" + str(head).split("(")[0].lower())
                    hpp.block(pending, 0)
                    hpp.fortran_comment(s, 0, "interface block not translated")
                pending = []
            else:
                self.report.add("untranslated", "specification:" + k)
                hpp.block(pending, 0)
                pending = []
                hpp.fortran_comment(s, 0, "not translated")
        hpp.block([c for c in pending if not str(c).startswith(BLANK_MARK)], 0)

        # procedures
        protos_pub, protos_priv = self.tr(), self.tr()
        subs = [p for p in mod.node.content if cls(p) == "Module_Subprogram_Part"]
        fixture = None
        for s in (subs[0].content if subs else []):
            k = cls(s)
            if k == "Comment":
                cpp.comment(s, 0)
                continue
            if k not in ("Subroutine_Subprogram", "Function_Subprogram"):
                continue
            p = mod.procs[lname([c for c in s.content if cls(c) != "Comment"][0].items[1])]
            ptr = self.tr(p)
            if mod.is_test:
                role = pf_role(p)
                fixture = fixture or ("fixture" if any(pf_role(q) in ("before", "after")
                                                       for q in mod.procs.values()) else "")
                if role == "test":
                    self.doc(cpp, p, 0)
                    macro = f"TEST_F({mod.name}, {p.cname})" if fixture else f"TEST({mod.name}, {p.cname})"
                    self.emit_proc(cpp, p, 0, head=macro)
                else:
                    protos_priv.emit(0, self.proto(ptr, p) + ";")
                    self.doc(cpp, p, 0)
                    self.emit_proc(cpp, p, 0)
                cpp.emit(0, "")
                continue
            public = mod.is_public((p.generic or p.name).lower()) or mod.is_public(p.name)
            if p.method_of:
                self.doc(cpp, p, 0) if not public else None
                self.emit_proc(cpp, p, 0)
            elif public:
                self.doc(protos_pub, p, 0)
                self.warn_name(protos_pub, p.generic or p.name, 0)
                protos_pub.emit(0, self.proto(ptr, p) + ";")
                self.emit_proc(cpp, p, 0)
            else:
                self.warn_name(protos_priv, p.generic or p.name, 1)
                protos_priv.emit(1, self.proto(ptr, p) + ";")
                cpp.emit(0, "namespace {")
                self.doc(cpp, p, 0)
                self.emit_proc(cpp, p, 0)
                cpp.emit(0, "}  // namespace")
            cpp.emit(0, "")

        self.missing_modules()
        if mod.is_test:
            return None, self.assemble_test(top, dirs, cpp_priv, protos_priv, cpp, fixture, mod_doc)

        guard_text = "\n".join(hpp.out + protos_pub.out)
        h = self.file_header(top, cfg["header_ext"]) + \
            [BANNER.format(src=os.path.basename(self.src)), "#pragma once", ""]
        h += self.std_includes(guard_text, [("functional", ["std::reference_wrapper"]),
                                            ("memory", ["std::unique_ptr"]), ("optional", ["std::optional"]),
                                            ("string", ["std::string"]), ("vector", ["std::vector"]),
                                            ("cstdint", ["std::int"]), ("complex", ["std::complex"])])
        h += [f"#include {i}" for i in cfg["extra_includes"]] + self.includes()
        h += [""] + mod_doc.out + [self.open_ns(), ""]
        if len(types_fwd) > 1:
            h += types_fwd + [""]
        h += strip_blank(hpp.out)
        if protos_pub.out:
            h += [""] + protos_pub.out
        h += ["", f"}}  // namespace {self.ns}", ""]

        body = "\n".join(cpp.out + cpp_priv.out)
        c = self.file_header(top, cfg["source_ext"]) + \
            [BANNER.format(src=os.path.basename(self.src)), f'#include "{mod.name}{cfg["header_ext"]}"', ""]
        c += self.std_includes(body, [("algorithm", ["std::max", "std::min", "std::sort", "std::stable_sort"]),
                                      ("cmath", ["std::"]), ("limits", ["numeric_limits"]),
                                      ("stdexcept", ["throw std::"]),
                                      ("string", ["std::to_string"]), ("numeric", ["std::iota"]),
                                      ("utility", ["std::move"]), ("typeinfo", ["typeid("])])
        c += dirs.out + ["", self.open_ns(), ""] + self.using_other_ns()
        if cpp_priv.out or protos_priv.out:
            c += ["namespace {", ""] + strip_blank(cpp_priv.out) + ([""] if cpp_priv.out else []) + \
                 protos_priv.out + ["", "}  // namespace", ""]
        c += strip_blank(cpp.out) + ["", f"}}  // namespace {self.ns}", ""]
        return "\n".join(self.braces(squeeze(h))), "\n".join(self.braces(squeeze(c)))

    def missing_modules(self):
        """report used modules whose definitions are neither parsed (file or -I) nor mapped"""
        cfg = self.cfg
        mapped = set(cfg["function_map"]) | set(cfg["call_templates"]) | set(cfg["type_map"]) | \
            set(cfg["kind_map"])
        kinds = ("unknown-name", "external-call", "external-function", "unknown-type")
        unresolved = sorted({c.split(":", 1)[1] for c in self.report.cur["info"]
                             if c.split(":")[0] in kinds} - mapped)
        for u, only in self.mod.use_only.items():
            if u in self.prog.modules or u in cfg["ignore_modules"]:
                continue
            if only is not None:
                need = [n for n in dict.fromkeys(only) if n not in mapped]
                if need:
                    self.report.add("missing", f"{u}: needed for {', '.join(need)}")
            elif unresolved:
                self.report.add("missing", f"{u} (no only-list): unresolved names in this file: "
                                           f"{', '.join(unresolved)}")

    def braces(self, lines):
        """brace style: put the opening brace of blocks on its own line"""
        if self.cfg["brace_style"] != "allman":
            return lines
        out = []
        for line in lines:
            s = line.strip()
            if s.startswith("//") or s.startswith("#") or not s.endswith(" {") or s == "{":
                out.append(line)
                continue
            ind = line[:len(line) - len(line.lstrip())]
            head = s[:-2]
            if head.startswith("} "):           # } else {  /  } else if (...) {
                out.append(ind + "}")
                head = head[2:]
            out += [ind + head, ind + "{"]
        return out

    def file_header(self, top, ext):
        """file header comment of the Fortran source with the file name replaced"""
        import re
        new = self.mod.name + ext
        src = re.escape(os.path.basename(self.src))
        res = []
        for line in top.out:
            line = re.sub(src, new, line, flags=re.I)
            line = re.sub(r"(@file:?\s*)\S+\.(f90|f|pf)\b", lambda m: m.group(1) + new, line, flags=re.I)
            res.append(line)
        return res

    def assemble_test(self, top, dirs, cpp_priv, protos, cpp, fixture, mod_doc):
        mod = self.mod
        c = self.file_header(top, self.cfg["source_ext"]) + \
            [BANNER.format(src=os.path.basename(self.src)), "#include <gtest/gtest.h>", "", "#include <cmath>"]
        c += [f"#include {i}" for i in self.cfg["extra_includes"]] + self.includes() + dirs.out
        c += [""] + mod_doc.out + [self.open_ns(), ""] + self.using_other_ns()
        if cpp_priv.out or protos.out:
            c += ["namespace {", ""] + strip_blank(cpp_priv.out) + protos.out + ["", "}  // namespace", ""]
        if fixture:
            c += [f"class {mod.name} : public ::testing::Test {{", "protected:"]
            for p in mod.procs.values():
                role = pf_role(p)
                if role in ("before", "after"):
                    fn = "SetUp" if role == "before" else "TearDown"
                    c.append(f"  void {fn}() override {{ {p.cname}(); }}")
            c += ["};", ""]
        c += strip_blank(cpp.out) + ["", f"}}  // namespace {self.ns}", ""]
        return "\n".join(self.braces(squeeze(c)))


