def today(line):
    """the @date of a copied file header: the date of the generation (ISO, the format of the header is kept)"""
    import datetime
    return re.sub(r"(@date:?\s*)\S+", lambda m: m.group(1) + datetime.date.today().isoformat(), line)


BANNER = "// Generated by f2cpp from {src} -- review all TODO(f2cpp) markers."


class ModuleEmitter:
    def __init__(self, program, module, report, src_name):
        self.prog, self.mod, self.report, self.src = program, module, report, src_name
        self.cfg = program.cfg
        self.ns = program.namespace(module.name)

    def tr(self, proc=None):
        return Translator(self.prog, self.mod, proc, self.report)

    # ------------------------------------------------------------------ declarations
    def var_decl(self, tr, v, member=False):
        """declaration of a local / member / module variable (without trailing ';')"""
        t, st = tr.cpp_type(v), tr.storage(v)
        code = f"{t}\0{v.cname}"
        sizes = []
        for lo, hi in v.dims:
            if hi is None:
                sizes = []
                break
            if lo is None:
                sizes.append(tr.expr(hi).code)
            else:
                h, l = tr.expr(hi), tr.expr(lo)
                if l.code.lstrip("-").isdigit():
                    sizes.append(tr.minus(hi, int(l.code) - 1))
                else:
                    sizes.append(f"{par(h, 70)} - {par(l, 70, True)} + 1")
        if v.init is not None:
            if lname(v.init).replace(" ", "").endswith("null()"):
                return code + " = nullptr" if st == "ptr" else code
            if st == "stdvec" and cls(v.init) == "Array_Constructor":
                return f"{code} = {{{', '.join(i.code for i in tr.ac_items(v.init))}}}"
            x = tr.expr(v.init)
            if v.rank > 0 and x.rank == 0:
                if st != "eigen" or not sizes:
                    raise Untranslatable("array-initialisation")
                fn = "Zero" if is_zero(x.code) else "Constant"
                args = sizes if fn == "Zero" else sizes + [x.code]
                return f"{code} = {t}::{fn}({', '.join(args)})"
            return f"{code} = {tr.matrix(x)}"
        if st == "ptr":
            self.report.add("todo", "raw-pointer")
            return code + f" = nullptr /* {TODO}: non-owning Fortran pointer */"
        if sizes and not member:
            if st == "flat":
                return f"{code}({' * '.join(f'({d})' if not d.isalnum() else d for d in sizes)})"
            if st in ("eigen", "objmat"):
                return f"{code}({', '.join(sizes)})"
            if st in ("vec3", "stdvec"):
                return f"{code}({tr.nested_ctor(v, sizes)})"
        elif sizes and member:
            if st == "eigen":
                fn = f"{t}({', '.join(sizes)})"
                return f"{code} = {fn}"
            self.report.add("todo", "fixed-size-member")
            return code + f" /* {TODO}: fixed size ({', '.join(sizes)}) */"
        return code

    def decl_stmt(self, tr, stmt, vars_, ind, prefix="", skip=(), member=False, companions=True):
        """emit one Fortran declaration statement"""
        names = [lname(e.items[0]) for e in items_of(stmt.items[2])]
        decls = []          # [type, [declarators]]: entities of equal type share one statement
        for n in names:
            v = vars_[n]
            if n in skip or v.alias or (n == tr.err and v.base == "integer" and v.rank == 0) or v.named_elements:
                continue                        # named_elements: declared at the assignments of the elements
            if not member and tr.expanded_variables(v):     # expand_args type: its variables
                decls += [[prefix + d.rsplit(" ", 1)[0], [d.rsplit(" ", 1)[1] + ("{}" if tr.proc else "")]]
                          for d in tr.expanded_variables(v)]
                self.report.add("translated", "declaration")
                continue
            try:
                pre = prefix
                if v.mutable and member:
                    pre += "mutable "
                elif v.has("parameter"):
                    pre += "const "
                elif (v.has("save") or v.init is not None) and tr.proc is not None:
                    pre += "static "
                t, d = self.var_decl(tr, v, member).split("\0")
                t = pre + t
                if decls and decls[-1][0] == t and not t.endswith("*") and "/*" not in d:
                    decls[-1][1].append(d)
                else:
                    decls.append([t, [d]])
                for cv in (v.companions or {}).values() if companions else ():   # unwrapped type: other components
                    ct, cd = self.var_decl(tr, cv, member).split("\0")
                    decls.append([pre + ct, [cd]])
                self.report.add("translated", "declaration")
            except Untranslatable as e:
                self.report.add("untranslated", "declaration:" + e.category)
                tr.fortran_comment(stmt, ind, f"declaration of '{v.cname}' not translated ({e.category})")
        for t, ds in decls:
            tr.emit(ind, f"{t} {', '.join(ds)};")
        self.warn_lower_bounds(tr, [vars_[n] for n in names if n not in skip], ind)

    def warn_lower_bounds(self, tr, variables, ind):
        """C++ arrays are 0-based; indices of arrays with a Fortran lower bound /= 1 are shifted"""
        for v in variables:
            if v.has("pointer") and v.rank > 0 and not v.alias:
                self.report.add("todo", "array-pointer")
                tr.emit(ind, f"// {TODO}: Fortran array pointer '{v.cname}' is translated as an owning array "
                             "(no aliasing of its target)")
            lbs = [str(lo).replace(" ", "") for lo, _ in v.dims if lo is not None]
            if any(not lb.lstrip("-").isdigit() for lb in lbs):     # constant bounds are shifted exactly
                self.report.add("todo", "lower-bound")
                tr.emit(ind, f"// {TODO}: '{v.cname}' has the variable lower bound(s) {', '.join(lbs)} in "
                             "Fortran; indices are shifted accordingly, check its uses")

    def signature(self, tr, p, decl, qualify=""):
        """-> (return type, name, parameter list, trailing qualifiers)"""
        params = []
        gone = tr.dropped(p)
        dummies = [a for a in p.args if a != tr.err and a != p.pass_arg and a not in gone]
        n_opt = 0
        for a in reversed(dummies):
            if p.vars[a].opt_kind:
                n_opt += 1
            else:
                break
        for i, a in enumerate(dummies):
            v = p.vars[a]
            if tr.expansion(v):                 # one argument -> several C++ parameters (expand_args)
                params += [f"{t} {n}" for t, n, _ in tr.expansion(v)]
                continue
            s = f"{tr.param_type(v)} {v.cname}"
            if decl and v.opt_kind and i >= len(dummies) - n_opt:
                s += f" = {tr.cpp_type(v)}()" if v.opt_kind == "empty" else " = std::nullopt"
            params.append(s)
        ret = "void"
        if p.kind == "function":
            ret = tr.cpp_type(p.vars[p.result]) if p.result in p.vars else "auto"
        name = qualify + (p.bind_name if p.method_of else (p.generic or p.cname))
        const = " const" if p.pass_arg and p.vars[p.pass_arg].intent == "in" else ""
        return ret, name, ", ".join(params), const

    def proto(self, tr, p, decl=True, qualify=""):
        ret, name, params, const = self.signature(tr, p, decl, qualify)
        tn = self.prog.type_name(p.method_of).split("::")[-1] if p.method_of else ""
        if name.endswith("~"):
            return f"{qualify}~{tn}()"
        if p.is_ctor:
            return f"{qualify}{tn}({params})"
        return f"{ret} {name}({params}){const}"

    def warn_name(self, tr, definition, references, ind):
        """the definition and the references that resolve to it (not just equal names) differ in case"""
        spellings = sorted({definition} | set(references))
        if len(spellings) > 1:
            self.report.add("todo", "inconsistent-name-case:" + ",".join(spellings))
            tr.emit(ind, f"// {TODO}: name is spelled inconsistently in the Fortran source: "
                         + ", ".join(spellings))

    def doc(self, tr, p, ind):
        for c in p.doc:
            if not str(c).startswith((PF_MARK, CPP_MARK, BLANK_MARK)):
                tr.comment(c, ind)
        dox, tags = self.cfg["doxygen"], {"in": "[in]", "out": "[out]", "inout": "[in,out]"}
        order = {a: i for i, a in enumerate(p.args)}
        for names, lines in sorted(p.param_docs, key=lambda d: order.get(d[0][0], len(order))):
            names = [n for n in names if n != tr.err and n != p.pass_arg and n not in tr.dropped(p)]
            if not names:
                continue
            if names == [p.result]:
                head = f"{dox} @return"
            else:
                v = p.vars[names[0]]
                head = f"{dox} @param{tags.get(v.intent, '')} {', '.join(p.vars[n].cname for n in names)}"
            tr.emit(ind, f"{head} {lines[0]}".rstrip())
            for line in lines[1:]:
                tr.emit(ind, f"{dox}   {line}".rstrip())

    # ------------------------------------------------------------------ class
    def emit_type(self, tr, t, ind):
        prog = self.prog
        name = prog.type_name(t.name)
        poly = prog.polymorphic(t)
        if prog.inconsistent_case(t.name):
            self.report.add("todo", "inconsistent-type-case:" + ",".join(sorted(prog.spellings[t.name])))
            tr.emit(ind, f"// {TODO}: type name is spelled inconsistently in the Fortran source: "
                         + ", ".join(sorted(prog.spellings[t.name])))
        base = f" : public {prog.type_name(t.parent, self.mod)}" if t.parent else ""
        final = " final" if not t.children and not t.abstract else ""
        tr.emit(ind, f"class {name}{final}{base} {{")
        tr.emit(ind, "public:")
        if t.parent and any(a.name in self.cfg["wrap_reverse_factories"] for a in prog.ancestors(t)):
            parent = prog.type_name(t.parent, self.mod)     # factory implemented in C++: its name constructor
            tr.emit(ind + 1, f"using {parent}::{parent.split('::')[-1]};")
        mine = [p for p in t.module.procs.values() if p.method_of == t.name]
        callbacks = [q for m in prog.modules.values() for q in m.procs.values()
                     if q.cb_method and prog.find_type(q.method_of, q.module) is t]
        has_dtor = any(p.bind_name == "~" for p in mine)
        if any(p.is_ctor for p in mine) or has_dtor:
            tr.emit(ind + 1, f"{name}() = default;")
        if has_dtor:    # a user-declared destructor suppresses the implicit move operations
            tr.emit(ind + 1, f"{name}(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}({name}&&) = default;")
            tr.emit(ind + 1, f"{name}& operator=(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}& operator=({name}&&) = default;")
        if not final and not has_dtor:          # coding rule: final or a virtual destructor
            if not any(p.is_ctor for p in mine):    # (declared copy / move suppress the default constructor)
                tr.emit(ind + 1, f"{name}() = default;")
            tr.emit(ind + 1, f"virtual ~{name}() = default;")
            # a user-declared destructor suppresses the implicit move operations
            tr.emit(ind + 1, f"{name}(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}({name}&&) = default;")
            tr.emit(ind + 1, f"{name}& operator=(const {name}&) = default;")
            tr.emit(ind + 1, f"{name}& operator=({name}&&) = default;")
        # flatten: fparser spreads components / comments over several nodes
        comps, binds = [], []
        for part in t.node.content[1:-1]:
            k = cls(part)
            if k == "Component_Part":
                comps += part.content
            elif k == "Comment":
                comps.append(part)
            elif k == "Type_Bound_Procedure_Part":
                n = [cls(c) for c in part.content].index("Contains_Stmt")
                comps += part.content[:n]
                binds += part.content[n + 1:]
        prev = None
        documented = set()          # bindings whose procedure has its own documentation
        for b in binds:
            if cls(b) == "Specific_Binding" and lname(b.items[3]) in t.bindings:
                q = prog.binding_proc(t, t.bindings[lname(b.items[3])])
                if q is not None and any(not str(c).startswith((PF_MARK, CPP_MARK, BLANK_MARK))
                                         for c in q.doc):
                    documented.add(id(b))
        hidden, pending = {0: [], 1: []}, None     # private bindings: (start in tr.out, level)

        def flush():
            if pending is not None:     # move the lines of a private binding into its section
                hidden[pending[1]].extend(tr.out[pending[0]:])
                del tr.out[pending[0]:]
        for b in binds:
            k = cls(b)
            trailing = k == "Comment" and prev is not None and b.item is not None and last_line(prev) == b.item.span[0]
            if not trailing:            # a trailing comment moves with its (private) binding
                flush()
                pending = None
            if k == "Comment":
                if trailing and id(prev) in documented:
                    continue        # short comment at the binding: the detailed one of the procedure is used
                tr.comment(b, ind + 1, prev if cls(prev) != "Binding_Private_Stmt" else None)
                continue
            prev = b
            if k == "Specific_Binding":
                bd = t.bindings[lname(b.items[3])]
                if self.excluded(f"{t.name}%{bd.name}"):
                    self.excluded_names.add(f"{t.name}%{bd.name}")
                    continue
                p = prog.binding_proc(t, bd)
                if p is None:
                    self.report.add("untranslated", "binding")
                    tr.fortran_comment(b, ind + 1, "binding to unknown procedure")
                    continue
                level = self.binding_level(t, bd, p)
                pending = (len(tr.out), level) if level < 2 else None
                ptr = self.tr(p)
                self.doc(tr, p, ind + 1)
                special = self.cfg["constructor_bindings"] + self.cfg["destructor_bindings"]
                if bd.deferred and bd.name in special:
                    tr.emit(ind + 1, f"// deferred '{bd.name}': constructor / destructor of the derived classes")
                    continue
                if bd.deferred:
                    # signature from the abstract interface, name from the binding
                    ret, _, params, const = self.signature(ptr, p, True)
                    self.warn_name(tr, bd.spelling, bd.spellings, ind + 1)
                    tr.emit(ind + 1, f"virtual {ret} {bd.spelling}({params}){const} = 0;")
                    continue
                if not (p.is_ctor or p.is_dtor):
                    self.warn_name(tr, bd.spelling, () if bd.generic else bd.spellings, ind + 1)
                sig = self.proto(ptr, p)
                if p.is_ctor:
                    sig = ("explicit " if sig.count(",") == 0 and not sig.endswith("()") else "") + sig
                elif p.is_dtor:
                    sig = sig if final else "virtual " + sig      # coding rule: final or a virtual destructor
                elif bd.nopass:
                    sig = "static " + sig
                elif poly:
                    if prog.overrides(t, bd.name):        # style: virtual ... override
                        sig = "virtual " + sig + " override" + (" final" if bd.non_overridable and not final else "")
                    elif prog.overridden(t, bd.name):
                        sig = "virtual " + sig
                tr.emit(ind + 1, sig + ";")
            elif k == "Final_Binding":
                tr.emit(ind + 1, f"~{name}();")
            elif k == "Generic_Binding":
                tr.emit(ind + 1, f"// generic '{lname(b.items[1])}': specific procedures are C++ overloads")
        flush()
        for q in callbacks:             # former callback implementations with user data of this type
            self.doc(tr, q, ind + 1)
            tr.emit(ind + 1, self.proto(self.tr(q), q) + ";")
        if t.comps or hidden[0] or hidden[1]:
            if binds or callbacks or (poly and not t.parent):
                tr.emit(0, "")
            # sections: 2 public, 1 protected, 0 private; each entry: comments before, statement,
            # component name (None: whole statement), comments behind
            # a plain data type (no methods) keeps public members: nothing else could use them
            methods = [b for b in t.bindings if f"{t.name}%{b}" not in self.excluded_names]
            modes = self.accessor_modes(t)
            self.emit_accessors(tr, t, modes, ind + 1)
            auto = self.cfg["member_access"] == "auto" and bool(methods or callbacks or t.parent)
            fixed = (1 if t.children else 0) if t.private_comps else 2
            sections, lead, last = {2: [], 1: [], 0: []}, [], None
            for d in comps:
                if cls(d) == "Comment":
                    if last is not None and d.item is not None and getattr(last[0][1], "item", None) is not None \
                            and last[0][1].item.span[1] == d.item.span[0]:
                        for entry in last:
                            entry[3].append(d)          # trailing comment of the previous statement
                    else:
                        lead.append(d)
                    continue
                if cls(d) == "Data_Component_Def_Stmt":
                    names = [lname(e.items[0]) for e in items_of(d.items[2])]
                elif cls(d) == "Proc_Component_Def_Stmt":
                    names = [lname(pd.items[0] if cls(pd) == "Proc_Decl" else pd) for pd in items_of(d.items[2])]
                else:
                    names = [None]
                last = []
                for k, n in enumerate(names):
                    level = (t.comps[n].access_need if auto else fixed) if n is not None else 2
                    if n in modes:                 # accessors: protected (private if final)
                        level = 0 if final else 1
                    entry = (lead if k == 0 else [], d, n, [])
                    sections[level].append(entry)
                    last.append(entry)
                lead = []
            if lead:
                sections[2].append((lead, None, None, []))
            for level in (1, 0):        # private bindings first in their section
                if hidden[level]:
                    sections[level].insert(0, ([], hidden[level], None, []))
            first = True
            for level, label in ((2, "public:"), (1, "protected:"), (0, "private:")):
                if not sections[level]:
                    continue
                if not (first and level == 2):          # the class starts with public:
                    if not first:
                        tr.emit(0, "")
                    tr.emit(ind, label)
                first = False
                for before, d, n, behind in sections[level]:
                    for c in before:
                        tr.comment(c, ind + 1)
                    if d is None:
                        continue
                    if isinstance(d, list):     # declarations of private bindings
                        tr.out.extend(d)
                        continue
                    v = t.comps.get(n) if n is not None else None
                    if getattr(self, "document_members", False) and v is not None and not before and not behind \
                            and not v.unwrapped_type:   # generated copies (wrapped modules): every member documented
                        tr.emit(ind + 1, f"{self.cfg['doxygen']} component {v.cname}")
                    if cls(d) == "Data_Component_Def_Stmt" and v is not None and v.unwrapped_type and \
                            not before and not behind:  # unwrapped type: documentation of its component
                        for line in self.member_docs(t, v):
                            tr.emit(ind + 1, f"{self.cfg['doxygen']} {line}".rstrip())
                    if cls(d) == "Data_Component_Def_Stmt" and n in modes:      # renamed: n_
                        ct, cd = self.var_decl(tr, v, True).split("\0")
                        tr.emit(ind + 1, f"{ct} {subst(self.cfg['member_name'], name=v.cname)}{cd[len(v.cname):]};")
                    elif cls(d) == "Data_Component_Def_Stmt":
                        one = type("S", (), {"items": (d.items[0], d.items[1], _One(d, n))})()
                        self.decl_stmt(tr, one, t.comps, ind + 1, member=True, companions=False)
                    elif cls(d) == "Proc_Component_Def_Stmt":       # procedure pointer: callable object
                        tr.emit(ind + 1, f"{tr.cpp_type(t.comps[n])} {t.comps[n].cname};")
                    else:
                        self.report.add("untranslated", "component:" + cls(d))
                        tr.fortran_comment(d, ind + 1, "component not translated")
                    for c in behind:
                        tr.comment(c, ind + 1, d)
                    for cv in (v.companions or {}).values() if v is not None else ():
                        for line in self.member_docs(t, cv):
                            tr.emit(ind + 1, f"{self.cfg['doxygen']} {line}".rstrip())
                        ct, cd = self.var_decl(tr, cv, True).split("\0")
                        tr.emit(ind + 1, f"{ct} {cd};")
        tr.emit(ind, "};")

    def binding_level(self, t, bd, p):
        """C++ section of a binding: 2 public, 1 protected, 0 private. Fortran private bindings (module-private) are
        private / protected / public by their calls (own methods / derived types / elsewhere); member_access =
        "fortran": private; constructors and destructors stay public"""
        private = bd.access == "private" or (bd.access is None and t.private_bindings)
        if not private or p.is_ctor or p.is_dtor:
            return 2
        return 0 if self.cfg["member_access"] == "fortran" else bd.access_need

    def accessor_modes(self, t):
        """{component: (getter name, setter name, get | set | ref)} of the accessors of t's own components"""
        m, res = self.cfg["accessors"].get(t.name, {}), {}
        if t.module.name not in getattr(self.prog, "translated", ()):     # e.g. C++ copies of struct constants
            return res
        for n, v in t.comps.items():
            ent = m.get(n) or m.get("*")
            if ent and v.base != "procedure" and not v.companions and not v.unwrapped:
                res[n] = tuple(ent[0] or subst(self.cfg[k], name=v.cname)
                               for k in ("member_getter_name", "member_setter_name")) + (ent[1],)
        return res

    def emit_accessors(self, tr, t, modes, ind):
        """public accessors of the members renamed to <name>_ (accessors of a translated class)"""
        cfg, docs = self.cfg, self.component_docs(t)
        dox = cfg["doxygen"]
        for n, (get, put, mode) in modes.items():
            v = t.comps[n]
            ty, m = tr.cpp_type(v), subst(cfg["member_name"], name=v.cname)
            snip = {"type": ty, "name": get, "member": m}
            plain = v.rank == 0 and v.base in ("real", "integer", "logical") and not v.ptr_like and not v.has("pointer")
            doc = docs.get(n, []) or [f"component {v.cname}"]

            def emit(decl, suffix="", doc=doc):
                lines = list(doc)
                lines[-1] += suffix
                for line in lines:
                    tr.emit(ind, f"{dox} {line}".rstrip())
                tr.emit(ind, decl)
            if mode == "ref":
                emit(subst(cfg["member_reference"], **snip))
            emit(subst(cfg["member_getter" if plain else "member_getter_ref"], **snip),
                 " (const version)" if mode == "ref" else "")
            if mode == "set":
                emit(subst(cfg["member_setter" if plain else "member_setter_ref"], **{**snip, "name": put}), " (setter)")
        if modes:
            tr.emit(0, "")

    def component_docs(self, t):
        """{component: [comment text]}: comments before the statement and behind it on the same line"""
        flat = []
        for part in t.node.content[1:-1]:       # fparser spreads components / comments over several nodes
            k = cls(part)
            if k == "Component_Part":
                flat += part.content
            elif k == "Comment":
                flat.append(part)
            elif k == "Type_Bound_Procedure_Part":     # comments before `contains` sit in it
                flat += part.content[:[cls(c) for c in part.content].index("Contains_Stmt")]
                break
        docs, lead, last = {}, [], []
        for d in flat:
            if cls(d) == "Comment":
                text = str(d)
                if not text.strip() or text.startswith((CPP_MARK, BLANK_MARK, PF_MARK)):
                    lead = []
                    continue
                text = re.sub(r"^![<>!]?\s?", "", text.strip()).rstrip()
                prev = last[-1][1] if last else None
                if prev is not None and d.item is not None and getattr(prev, "item", None) is not None \
                        and prev.item.span[1] == d.item.span[0]:
                    for n, _ in last:
                        docs[n].append(text)        # trailing comment of the previous statement
                else:
                    lead.append(text)
                continue
            names = [lname(e.items[0]) for e in items_of(d.items[2])] if cls(d) == "Data_Component_Def_Stmt" else []
            last = [(n, d) for n in names]
            for n in names:
                docs[n] = list(lead)
            lead = []
        return docs

    def member_docs(self, t, v):
        """documentation of component v of t; companions / unwrapped variables of unwrap_types without
        own documentation: that of the component of the unwrapped type"""
        own = self.component_docs(t).get(v.name) if t.node is not None else None
        if own or not (v.companion_of or v.unwrapped_type):
            return own or []
        inner = v.companion_of[1] if v.companion_of else v.unwrapped
        ut = self.prog.find_type(v.unwrapped_type, t.module)
        return self.component_docs(ut).get(inner, []) if ut is not None else []

    # ------------------------------------------------------------------ procedures
    def internal_order(self, p):
        """internal procedures in an order in which each lambda is defined before its use; the
        procedures that call themselves (directly or through others) cannot become lambdas"""
        from fparser.two.utils import walk
        from fparser.two import Fortran2003 as F
        deps = {}
        for q in p.internal.values():
            names = {lname(n.items[0]) for n in walk(q.node, (F.Call_Stmt, F.Function_Reference, F.Part_Ref,
                                                              F.Structure_Constructor))
                     if cls(n.items[0]) == "Name"}
            names |= {lname(n) for n in walk(q.node, F.Name)}       # also passed as actual argument
            deps[q.name] = {d for d in names if d in p.internal and d != q.name}
            if q.name in {lname(n.items[0]) for n in walk(q.node, (F.Call_Stmt, F.Function_Reference))
                          if cls(n.items[0]) == "Name"}:
                deps[q.name].add(q.name)                            # recursive
        order, done = [], set()
        while True:                         # source order as far as the dependencies allow
            ready = [n for n in deps if n not in done and deps[n] <= done]
            if not ready:
                break
            order.append(p.internal[ready[0]])
            done.add(ready[0])
        return order, [p.internal[n] for n in deps if n not in done]

    def emit_lambdas(self, tr, p, ind):
        """internal procedures -> lambdas capturing the host variables by reference"""
        order, rest = self.internal_order(p)
        for q in order:
            ptr = self.tr(q)
            ret, _, params, _ = self.signature(ptr, q, True)
            self.doc(tr, q, ind)
            head = f"auto {q.cname} = [&]({params})" + (f" -> {ret}" if q.kind == "function" else "")
            self.emit_proc(tr, q, ind, head=head, close="};")
            tr.emit(0, "")
        for q in rest:
            self.report.add("untranslated", "recursive-internal-procedure")
            tr.fortran_comment(q.node, ind, "recursive internal procedure (a lambda cannot call itself)")

