def plain_comment(line):
    """doxygen comment line -> ordinary comment line"""
    s = line.lstrip()
    return line[:len(line) - len(s)] + ("//" + s[4:] if s.startswith("///<") else "//" + s[3:]
                                        if s.startswith("///") else s)


def pf_role(p):
    for c in p.doc:
        s = str(c)
        if s.startswith(PF_MARK):
            return s[len(PF_MARK):].split()[0].split("(")[0]
    return None


def strip_blank(lines):
    lines = list(lines)
    while lines and lines[0] == "":
        lines.pop(0)
    while lines and lines[-1] == "":
        lines.pop()
    return lines


def squeeze(lines):
    out = []
    for line in lines:
        if line == "" and out and out[-1] == "":
            continue
        out.append(line)
    return out
