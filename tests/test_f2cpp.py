def run(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    assert r.returncode == 0, f"{' '.join(cmd)}\n{r.stdout}\n{r.stderr}"
    return r.stdout


def cfg(**kw):
    return config.load(os.path.join(SUPPORT, "f2cpp.toml"), **kw)


