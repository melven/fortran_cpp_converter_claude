#!/usr/bin/env python3
"""Generate an f2cpp function_map for the TIXI XML library from its C header.

usage: make_tixi_config.py /path/to/tixi/src/tixi.h > examples/tixi.toml

The Fortran 2003 binding of TIXI (bindings/fortran03) has the same function names and
argument order as the C API. Translated code can therefore call the C API directly if the
arguments are converted: strings to const char*, output arguments to pointers, arrays to
data pointers.
"""
import re
import sys


def conversion(arg):
    arg = re.sub(r"\s+", " ", arg.strip())
    stars = arg.count("*")
    base = arg.replace("*", " ")
    const = base.startswith("const ")
    if "char" in base.split():
        return "cstr" if stars == 1 and const else "ptr"     # char** etc.: output string(s)
    if stars == 0:
        return ""
    if stars == 1 and const:
        return "data"                                        # const double*: input array
    return "ptr"                                             # int*, double*, double**: output


def main(header):
    text = open(header).read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    entries, review = [], []
    for m in re.finditer(r"DLL_EXPORT\s+([\w\s\*]+?)\s*\b(tixi\w+)\s*\(([^;{]*?)\)\s*;", text):
        name, args = m.group(2), m.group(3).strip()
        args = [] if args in ("", "void") else [a for a in args.split(",")]
        parts = []
        for i, a in enumerate(args):
            conv = conversion(a)
            parts.append(f"{{{i}:{conv}}}" if conv else f"{{{i}}}")
            if conv == "ptr" and ("char" in a or a.count("*") > 1):
                review.append(name)
        entries.append((name, f"{name}({', '.join(parts)})"))
    print("# f2cpp function_map for the TIXI XML library, generated by tools/make_tixi_config.py")
    print("# from tixi.h: the Fortran 2003 binding and the C API share names and argument order.")
    print("# {i:cstr}: std::string -> const char*, {i:ptr}: address of an output argument,")
    print("# {i:data}: data pointer of an Eigen array.")
    print("#")
    print("# Check by hand (output strings / arrays, Fortran used character or array pointers):")
    for name in sorted(set(review)):
        print(f"#   {name}")
    print()
    print("ignore_modules = [\"tixi\"]        # appended to the defaults; the C header replaces the module")
    print("extra_includes = ['<tixi.h>']")
    print()
    print("[function_map]")
    for name, template in entries:
        print(f'{name} = "{template}"')


if __name__ == "__main__":
    main(sys.argv[1])
